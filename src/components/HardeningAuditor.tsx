import React, { useState } from 'react';
import { INI_HARDENING_DIRECTIVES } from '../data/hardeningGuide';
import { Shield, Copy, Check, CheckCircle2, AlertTriangle, Download, RefreshCw } from 'lucide-react';

export const HardeningAuditor: React.FC = () => {
  // Config state: key -> current value
  const [config, setConfig] = useState<Record<string, string>>(() => {
    const initial: Record<string, string> = {};
    INI_HARDENING_DIRECTIVES.forEach((d) => {
      initial[d.key] = d.recommended;
    });
    return initial;
  });

  const [copied, setCopied] = useState<boolean>(false);

  // Calculate score
  const totalDirectives = INI_HARDENING_DIRECTIVES.length;
  let secureCount = 0;
  INI_HARDENING_DIRECTIVES.forEach((d) => {
    if (config[d.key] === d.recommended) {
      secureCount++;
    }
  });
  const securityScore = Math.round((secureCount / totalDirectives) * 100);

  const handleApplyRecommended = () => {
    const recommended: Record<string, string> = {};
    INI_HARDENING_DIRECTIVES.forEach((d) => {
      recommended[d.key] = d.recommended;
    });
    setConfig(recommended);
  };

  const handleResetDefaults = () => {
    const defaults: Record<string, string> = {};
    INI_HARDENING_DIRECTIVES.forEach((d) => {
      defaults[d.key] = d.default;
    });
    setConfig(defaults);
  };

  const generateIniContent = () => {
    let out = `; ====================================================================\n`;
    out += `; PHP Production Hardening Blueprint (Auto-generated by PHP VulnLab)\n`;
    out += `; Defense-in-depth configuration for high-security environments\n`;
    out += `; ====================================================================\n\n`;

    const categories = ['Code Execution', 'File System', 'Session & Cookies', 'Information Leakage'] as const;

    categories.forEach((cat) => {
      out += `[${cat.toUpperCase()}]\n`;
      const catDirectives = INI_HARDENING_DIRECTIVES.filter((d) => d.category === cat);
      catDirectives.forEach((d) => {
        out += `; ${d.description}\n`;
        out += `${d.key} = ${config[d.key]}\n\n`;
      });
    });

    return out;
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(generateIniContent());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([generateIniContent()], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'php.ini';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Overview & Score Card */}
      <div className="p-5 bg-slate-900 border border-slate-800 rounded-xl flex flex-wrap items-center justify-between gap-4">
        <div className="space-y-1">
          <div className="flex items-center gap-2">
            <Shield className="w-5 h-5 text-indigo-400" />
            <h2 className="text-base font-bold text-white">Interactive php.ini Hardening Auditor</h2>
          </div>
          <p className="text-xs text-slate-300 max-w-2xl leading-relaxed">
            Misconfigured PHP directives are the primary enabler of Remote File Inclusion (RFI), command execution sinks, and session hijacking. Audit your configuration against production security benchmarks.
          </p>
        </div>

        {/* Security Gauge */}
        <div className="flex items-center gap-4 bg-slate-950 p-3 rounded-lg border border-slate-800">
          <div>
            <div className="text-[11px] text-slate-400 uppercase tracking-wider font-semibold">
              Security Posture
            </div>
            <div className="flex items-baseline gap-2">
              <span className={`text-2xl font-bold font-mono tabular-nums ${
                securityScore >= 90 ? 'text-emerald-400' : securityScore >= 60 ? 'text-amber-400' : 'text-rose-400'
              }`}>
                {securityScore}%
              </span>
              <span className="text-xs text-slate-400">
                ({secureCount}/{totalDirectives} secured)
              </span>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleApplyRecommended}
              className="px-3 py-1.5 text-xs font-semibold text-white bg-indigo-600 hover:bg-indigo-500 rounded-lg transition-colors whitespace-nowrap"
            >
              Apply All Recommended
            </button>
            <button
              onClick={handleResetDefaults}
              className="p-1.5 text-slate-400 hover:text-slate-200 hover:bg-slate-800 rounded-lg transition-colors"
              title="Reset to default unhardened state"
            >
              <RefreshCw className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>

      {/* Directives Configuration Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {INI_HARDENING_DIRECTIVES.map((directive) => {
          const currentVal = config[directive.key];
          const isHardened = currentVal === directive.recommended;

          return (
            <div
              key={directive.key}
              className={`p-4 rounded-xl border transition-all text-xs space-y-2.5 ${
                isHardened
                  ? 'bg-slate-900/80 border-slate-800'
                  : 'bg-slate-900 border-amber-800/80'
              }`}
            >
              <div className="flex items-start justify-between gap-2">
                <div>
                  <div className="flex items-center gap-2">
                    <span className="font-mono font-bold text-slate-200 text-sm">
                      {directive.key}
                    </span>
                    <span className="text-[10px] text-slate-400">
                      {directive.category}
                    </span>
                  </div>
                  <p className="text-slate-400 mt-1 leading-snug">
                    {directive.description}
                  </p>
                </div>

                <div className="shrink-0 flex items-center">
                  {isHardened ? (
                    <span className="flex items-center gap-1 text-[11px] font-semibold text-emerald-400 bg-emerald-950/60 border border-emerald-800/60 px-2 py-0.5 rounded">
                      <CheckCircle2 className="w-3 h-3" />
                      Hardened
                    </span>
                  ) : (
                    <span className="flex items-center gap-1 text-[11px] font-semibold text-amber-400 bg-amber-950/60 border border-amber-800/60 px-2 py-0.5 rounded">
                      <AlertTriangle className="w-3 h-3" />
                      Insecure
                    </span>
                  )}
                </div>
              </div>

              {/* Toggle / Setting Selector */}
              <div className="pt-1 flex items-center justify-between gap-3 bg-slate-950/60 p-2.5 rounded-lg border border-slate-800/80">
                <span className="text-slate-400 font-mono text-[11px]">
                  Setting: <strong className="text-indigo-300">{currentVal || 'empty'}</strong>
                </span>

                <div className="flex items-center gap-1.5">
                  <button
                    onClick={() => setConfig({ ...config, [directive.key]: directive.recommended })}
                    className={`px-2.5 py-1 rounded text-[11px] font-medium transition-colors ${
                      isHardened
                        ? 'bg-indigo-600 text-white'
                        : 'bg-slate-800 text-slate-300 hover:bg-slate-700'
                    }`}
                  >
                    Recommended ({directive.recommended.length > 15 ? 'Secure List' : directive.recommended})
                  </button>

                  <button
                    onClick={() => setConfig({ ...config, [directive.key]: directive.default })}
                    className={`px-2.5 py-1 rounded text-[11px] font-medium transition-colors ${
                      !isHardened
                        ? 'bg-amber-900 text-amber-200'
                        : 'bg-slate-800 text-slate-400 hover:text-slate-300'
                    }`}
                  >
                    Default ({directive.default || 'Off'})
                  </button>
                </div>
              </div>

              {/* Risk Callout if Insecure */}
              {!isHardened && (
                <div className="text-[11px] text-amber-300/90 bg-amber-950/30 p-2 rounded border border-amber-900/40 leading-snug">
                  <strong>Risk:</strong> {directive.riskIfMisconfigured}
                </div>
              )}
            </div>
          );
        })}
      </div>

      {/* Generated php.ini File Viewer */}
      <div className="bg-slate-900 border border-slate-800 rounded-xl overflow-hidden space-y-0">
        <div className="flex items-center justify-between px-4 py-3 border-b border-slate-800 bg-slate-950">
          <div className="flex items-center gap-2 text-xs font-semibold text-slate-200">
            <Shield className="w-4 h-4 text-indigo-400" />
            <span>Generated Hardened php.ini Configuration</span>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs text-slate-200 bg-slate-800 hover:bg-slate-700 rounded-lg transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-400" />
                  <span className="text-emerald-400">Copied</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy php.ini</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-white bg-indigo-600 hover:bg-indigo-500 rounded-lg transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download</span>
            </button>
          </div>
        </div>

        <pre className="p-4 bg-slate-950 font-mono text-xs text-indigo-200/90 max-h-80 overflow-y-auto leading-relaxed">
          {generateIniContent()}
        </pre>
      </div>
    </div>
  );
};
